// lặp lại động từ: AA, A一A, A了A, ABAB (bỏ các từ vốn là chữ lặp như 妈妈, 谢谢)
const NOT_RED = new Set([...'妈爸哥姐弟妹奶爷谢星宝人天常刚渐个样了在是的不']);
const KNOWN_ABAB = /(休息|学习|介绍|准备|打扫|收拾|商量|研究|考虑|练习|讨论|检查|帮助|锻炼|活动|整理|认识|了解|高兴|干净|漂亮|明白|热闹|舒服|安静)\1/u;
function chongdie(z) {
  const m = z.match(KNOWN_ABAB); if (m) return m[0];
  for (const x of z.matchAll(/([一-鿿])([一了]?)\1/gu)) if (!NOT_RED.has(x[1])) return x[0];
  return '';
}

const COVERS = {
  'g3-jieci': ['g1-zai'], 'g2-zhengzai': ['g1-zai'], 'g3-yijiu': ['g2-jiu'], 'g3-yaoshi': ['g2-jiu'], 'g3-ruguo': ['g2-jiu'],
  'g3-lian': ['g1-dou'], 'g3-renzhi': ['g1-dou', 'g1-qw'], 'g3-zhiyou': ['g3-zhi', 'g3-cai'], 'g2-deshihou': ['g1-de'],
  'g1-taile': ['g1-le'], 'g2-buleba': ['g1-le'], 'g3-fanwen': ['g1-ma'], 'g1-zenmeyang': ['g1-ma'], 'g3-youyou': ['g2-zai-you'],
  'g1-shide': ['g1-shi'], 'g2-haimei': ['g2-ye-hai'], 'g3-yue': [], 'g3-kn': ['g3-kq'],
};
export function detectGrammar(z) {
  z = String(z || '');
  const out = [];
  for (const g of GRAMMAR) {
    let m = '';
    if (g.id === 'g3-chongdie') m = chongdie(z);
    else if (g.id in RX) { const rx = RX[g.id]; if (!rx) continue; const x = z.match(rx); m = x ? x[0] : ''; }
    else if (g.key && z.includes(g.key)) m = g.key;
    if (m) out.push({ g, m, at: z.indexOf(m) });
  }
  // điểm lớn đã bao gồm điểm nhỏ: bỏ điểm nhỏ cho đỡ rối (vd. 放在 → không hiện thêm 在 + địa điểm)
  const has = new Set(out.map(d => d.g.id)), drop = new Set();
  for (const [big, small] of Object.entries(COVERS)) if (has.has(big)) small.forEach(x => drop.add(x));
  for (let i = out.length - 1; i >= 0; i--) if (drop.has(out[i].g.id)) out.splice(i, 1);
  // điểm khó hơn lên trước; cùng cấp thì theo vị trí trong câu
  return out.sort((a, b) => b.g.level - a.g.level || a.at - b.at);
}
